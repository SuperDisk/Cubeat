#!/usr/bin/env python3
"""Cuts elias/assets/game-over.png into letters for the game over animation.

Writes src/res/anim_gameover.png (the letters as 8x16 sprite tiles, GAME low
in its tiles and OVER high: their sprites are stacked, so that the two rows
never share a scanline, and the empty rows of OVER's are the gap) and prints
which sprites to draw where on each frame of the animation: that goes in the
"Game over" section of src/engine.asm. Run it by hand from the root of the
repo when the art changes.
"""
from PIL import Image
import numpy as np

LIGHT, DARK = 1, 2            # sprite colors: 2 is the HUD's shadow color
RGB = {0: (255, 0, 255), LIGHT: (0xD3, 0xE2, 0x9A), DARK: (0x23, 0x43, 0x31)}
GAP = 0                       # extra pixels between letters once expanded
LINE_GAP = 2                  # transparent rows between GAME and OVER
# How far the letters are from the middle on each frame, in 1/16ths of their
# final distance: they burst out of the middle, overshoot and settle.
EASE = [0, 2, 4, 6, 8, 10, 12, 14, 16, 17, 18, 18, 17, 16]

src = np.array(Image.open("elias/assets/game-over.png"))
light = src == 3
H, W = light.shape

# Letters = connected groups of light pixels, except where two letters touch:
# (row, the two columns the cut goes between)
CUTS = {(9, 10, 11), (8, 20, 21), (9, 20, 21)}  # G|A and A|M
label = np.zeros((H, W), int)
n = 0
for y0 in range(H):
    for x0 in range(W):
        if not light[y0, x0] or label[y0, x0]:
            continue
        n += 1
        todo = [(y0, x0)]
        label[y0, x0] = n
        while todo:
            y, x = todo.pop()
            for dy, dx in ((0, 1), (0, -1), (1, 0), (-1, 0)):
                yy, xx = y + dy, x + dx
                if not (0 <= yy < H and 0 <= xx < W) or not light[yy, xx] or label[yy, xx]:
                    continue
                if dy == 0 and (y, min(x, xx), max(x, xx)) in CUTS:
                    continue
                label[yy, xx] = n
                todo.append((yy, xx))
letters = sorted(range(1, n + 1), key=lambda i: np.argwhere(label == i)[:, 1].min())
assert len(letters) == 8, len(letters)

# The shadow is to the left of and below the letters: each of its pixels
# belongs to the letter it is the shadow of.
dark = src == 0
for y, x in np.argwhere(dark):
    for dy, dx in ((0, 1), (-1, 0), (-1, 1)):
        yy, xx = y + dy, x + dx
        if 0 <= yy < H and 0 <= xx < W and light[yy, xx]:
            label[y, x] = label[yy, xx]
            break
    else:
        raise SystemExit(f"shadow pixel {x},{y} belongs to no letter")

def glyph(i):
    """The letter as drawn: (x of its left edge in the source, pixels)."""
    ys, xs = np.nonzero(label == i)
    x0 = xs.min()
    g = np.zeros((H, xs.max() - x0 + 1), int)
    for y, x in zip(ys, xs):
        g[y, x - x0] = LIGHT if light[y, x] else DARK
    return x0, g

glyphs = [glyph(i) for i in letters]
GH = H
tiles = []                    # 8x16 arrays
sprites = []                  # (line, letter, x within the line, tile)
for line in range(2):
    row0 = 16 - GH if line == 0 else LINE_GAP
    base = glyphs[line * 4][0]
    for k in range(4):
        x0, g = glyphs[line * 4 + k]
        for sx in range(0, g.shape[1], 8):
            t = np.zeros((16, 8), int)
            part = g[:, sx:sx + 8]
            t[row0:row0 + GH, :part.shape[1]] = part
            for j, u in enumerate(tiles):
                if (u == t).all():
                    break
            else:
                j = len(tiles)
                tiles.append(t)
            sprites.append((line, k, x0 - base + sx + k * GAP, j))

sheet = np.zeros((16, 8 * len(tiles), 3), np.uint8)
for j, t in enumerate(tiles):
    for y in range(16):
        for x in range(8):
            sheet[y, j * 8 + x] = RGB[t[y, x]]
Image.fromarray(sheet).save("src/res/anim_gameover.png")

width = max(glyphs[l * 4 + 3][0] - glyphs[l * 4][0] + glyphs[l * 4 + 3][1].shape[1] + 3 * GAP for l in range(2))
mid = width // 2
import sys
with sys.stdout as f:
    f.write(";; The sprites and frames below are generated by tools/mk_gameover.py\n\n")
    f.write(f"DEF GAMEOVER_SPRITES_GAME = {sum(1 for s in sprites if s[0] == 0)}\n")
    f.write(f"DEF GAMEOVER_SPRITES_OVER = {sum(1 for s in sprites if s[0] == 1)}\n")
    f.write(f"DEF GAMEOVER_TILES = {len(tiles) * 2}\n")
    f.write(f"DEF GAMEOVER_FRAMES = {len(EASE)}\n")
    f.write(f"DEF GAMEOVER_WIDTH = {width}\n")
    f.write(f"DEF GAMEOVER_HEIGHT = {GH * 2 + LINE_GAP}\n")
    f.write(f"DEF GAMEOVER_TOP = {16 - GH} ; rows of GAME's sprites above the text\n")
    f.write("DEF GAMEOVER_X = 80 - GAMEOVER_WIDTH / 2\n")
    f.write("DEF GAMEOVER_Y = 72 - GAMEOVER_HEIGHT / 2 - GAMEOVER_TOP\n\n")
    f.write(";; Y, tile pair\n")
    f.write("gameover_sprites:\n")
    for line, k, x, j in sprites:
        f.write(f"  gameover_sprite {line * 16}, {j}\n")
    for word in range(2):
        f.write(f"\n;; X of {'GAME' if word == 0 else 'OVER'}'s sprites, per frame\n")
        f.write(f"gameover_frames_{'game' if word == 0 else 'over'}:\n")
        for e in EASE:
            xs = []
            for line, k, x, j in sprites:
                if line != word:
                    continue
                # move the whole letter by the offset of its centre
                lx = [s[2] for s in sprites if s[0] == line and s[1] == k]
                c = (min(lx) + max(lx) + 8) / 2
                xs.append(round(x + (c - mid) * (e - 16) / 16))
            f.write("  db " + ", ".join(str(v) for v in xs) + "\n")
